package apply

import (
	"context"
	"fmt"
	"net/http"
	"path/filepath"
	"strings"
)

// testUsers creates the dev accounts with verified emails. Only dev config
// lists any.
func (a *Applier) testUsers(ctx context.Context) error {
	for _, u := range a.cfg.TestUsers {
		if u.Password == "" {
			return fmt.Errorf("test user %s has no password", u.Username)
		}
		id, err := a.findUser(ctx, u.Username)
		if err != nil {
			return err
		}
		key := "user:" + u.Username
		pw := hash(u.Password)
		if id == "" {
			in := obj{
				"username":     u.Username,
				"organization": obj{"orgId": a.readersID},
				"profile": obj{
					"givenName":         u.GivenName,
					"familyName":        u.FamilyName,
					"displayName":       strings.TrimSpace(u.GivenName + " " + u.FamilyName),
					"preferredLanguage": u.Language,
				},
				"email":    obj{"email": u.Email, "isVerified": true},
				"password": obj{"password": u.Password, "changeRequired": false},
			}
			if err := a.call(ctx, http.MethodPost, "/v2/users/human", "", in, nil); err != nil {
				return err
			}
			a.state.Hashes[key] = pw
			a.changed("test user %s created", u.Username)
			continue
		}
		if a.state.Hashes[key] != pw {
			in := obj{"newPassword": obj{"password": u.Password, "changeRequired": false}}
			if err := a.call(ctx, http.MethodPost, "/v2/users/"+id+"/password", "", in, nil); err != nil {
				return err
			}
			a.state.Hashes[key] = pw
			a.changed("test user %s password set", u.Username)
		}
	}
	return nil
}

// writeOutputs writes one env file per app and, when there are test users,
// users.txt. Everything goes to the gitignored output directory.
func (a *Applier) writeOutputs() error {
	ctx := context.Background()
	for _, app := range a.cfg.Apps {
		p := strings.ToUpper(app.Key)
		st := a.state.Apps[app.Key]
		key, err := a.signingKey(ctx, app.Key)
		if err != nil {
			return err
		}
		var b strings.Builder
		fmt.Fprintf(&b, "# Generated by identity-init (%s). Do not commit.\n", a.cfg.Environment)
		fmt.Fprintf(&b, "%s_OIDC_ISSUER=%s\n", p, a.cfg.Issuer)
		fmt.Fprintf(&b, "%s_OIDC_CLIENT_ID=%s\n", p, st.ClientID)
		fmt.Fprintf(&b, "%s_OIDC_CLIENT_SECRET=%s\n", p, st.ClientSecret)
		fmt.Fprintf(&b, "%s_IDP_WEBHOOK_SECRET=%s\n", p, key)
		fmt.Fprintf(&b, "%s_IDP_API_TOKEN=%s\n", p, a.state.Machines[app.Key].Token)
		if err := writeSecret(filepath.Join(a.outDir, app.Key+".env"), []byte(b.String())); err != nil {
			return err
		}
	}
	if len(a.cfg.TestUsers) == 0 {
		return nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Test users in org %q of %s. Sign in with the username or the email.\n", a.cfg.Orgs.Readers, a.cfg.Issuer)
	fmt.Fprintf(&b, "# username\temail\tpassword\tsub\n")
	for _, u := range a.cfg.TestUsers {
		id, err := a.findUser(ctx, u.Username)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\n", u.Username, u.Email, u.Password, id)
	}
	return writeSecret(filepath.Join(a.outDir, "users.txt"), []byte(b.String()))
}
